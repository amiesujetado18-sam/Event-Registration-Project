    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        String id = searchField.getText().trim();
            if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter a Participant ID.");
    return;
}

        Participant participant = participantArray.searchById(id);

            if (participant == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
            "Participant not found.");
} else {
          javax.swing.JOptionPane.showMessageDialog(this,
            "Participant Found!\n" + "ID: " + participant.getParticipantId() + "\nName: " + participant.getFullName() + "\nEmail: " + participant.getEmail() + "\nStatus: " + participant.getRegistrationStatus());
}
    }//GEN-LAST:event_searchButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        String id = searchField.getText().trim();
        String newStatus = statusComboBox.getSelectedItem().toString();

        if (id.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Please search or enter a Participant ID first.");
    return;
}

        if (participantArray.updateStatus(id, newStatus)) {

        javax.swing.JOptionPane.showMessageDialog(this,
            "Registration status updated successfully!");

    refreshTable();

} else {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Participant not found.");
}
    }//GEN-LAST:event_updateButtonActionPerformed
        
    private void refreshTable() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) participantTable.getModel();

    model.setRowCount(0);

    for (int i = 0; i < participantArray.getCount(); i++) {

        Participant p = participantArray.getParticipant(i);

        String type;
        String extra;
        String course = "";

        if (p instanceof StudentParticipant) {

            StudentParticipant student = (StudentParticipant) p;

            type = "Student";
            extra = student.getStudentId();
            course = student.getCourse();

        } else {

            GuestParticipant guest = (GuestParticipant) p;

            type = "Guest";
            extra = guest.getOrganization();
        }

        model.addRow(new Object[]{
            p.getParticipantId(),
            p.getFullName(),
            p.getEmail(),
            type,
            extra,
            course,
            p.getRegistrationStatus()
        });
    }
}

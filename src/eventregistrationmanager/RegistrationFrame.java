    private void registerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerButtonActionPerformed
       String id = participantIdField.getText().trim();
       String name = nameField.getText().trim();
       String email = emailField.getText().trim();
       String type = typeComboBox.getSelectedItem().toString();

       if (id.isEmpty() || name.isEmpty() || email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
       "Please fill in the required fields.");
       return;
}

Participant participant;

if (type.equals("Student")) {
    String studentId = studentIdField.getText().trim();
    String course = courseField.getText().trim();

    if (studentId.isEmpty() || course.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter the Student ID and Course.");
        return;
    }

    participant = new StudentParticipant(
            id, name, email, "Pending", studentId, course);

} else {
    String organization = organizationField.getText().trim();

    if (organization.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter the Organization.");
        return;
    }

    participant = new GuestParticipant(
            id, name, email, "Pending", organization);
}

if (participantArray.addParticipant(participant)) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Participant registered successfully!");
    refreshTable();
} else {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Registration failed. The ID may already exist or the array is full.");
}
    }//GEN-LAST:event_registerButtonActionPerformed

